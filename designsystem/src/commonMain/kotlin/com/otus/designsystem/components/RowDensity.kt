/**
 * How much room a [SettingRow] takes. [Regular] rows are settings rows with hairlines between
 * them. [Compact] rows are about 44 dp tall without hairlines, for long pickers such as a folder
 * list, where more rows on screen matter more than separation.
 */
public enum class RowDensity { Regular, Compact }
