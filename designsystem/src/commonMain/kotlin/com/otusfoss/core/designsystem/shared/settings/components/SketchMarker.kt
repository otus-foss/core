package com.otusfoss.core.designsystem.shared.settings.components

/** The mark at the start of a [PreviewCard]'s page sketch, hinting at the page it stands for. */
public enum class SketchMarker {
    /** A page without rows, such as an open message. */
    None,

    /** A row in a list. */
    Row,

    /** A selected row in a list. */
    Selected,
}
